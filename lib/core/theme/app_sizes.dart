import 'package:flutter_screenutil/flutter_screenutil.dart';

class AppSizes {
  AppSizes._();

  // Height
  static double h(num value) => value.h;

  // Width
  static double w(num value) => value.w;
  // Radius
  static double r(num value) => value.r;
  // Font size
  static double sp(num value) => value.sp;
}
